PRESSURE_DEVICE_OBJECT_TYPES = frozenset({
    "vessel",
    "gas_separator",
    "underground_tank",
    "oil_settler",
    "receiver",
    "газосепаратор",
    "ёмкость",
    "емкость",
    "отстойник",
})


def _attrs(equipment_data: Dict[str, Any]) -> Dict[str, Any]:
    raw = equipment_data.get("attributes") or {}
    return raw if isinstance(raw, dict) else {}


def _hay(*parts: str) -> str:
    return " ".join(p for p in parts if p).upper()


def detect_pressure_device_kind(equipment_data: Dict[str, Any]) -> str:
    """vessel | gas_separator | underground_tank | oil_settler | receiver"""
    return kind_from_preset(preset_from_equipment_data(equipment_data))


def is_pressure_device(equipment_data: Dict[str, Any]) -> bool:
    """Сосуд / газосепаратор / ёмкость / ресивер — единый шаблон отчёта СРпД."""
    code = (equipment_data.get("type_code") or "").upper()
    name = (equipment_data.get("type_name") or "").upper()
    eq_name = (equipment_data.get("name") or "").upper()
    kind = detect_pressure_device_kind(equipment_data)
    if kind != "vessel":
        return True
    attrs = _attrs(equipment_data)
    object_type = str(attrs.get("object_type") or "").lower()
    return (
        "VESSEL" in code
        or "РЕСИВЕР" in name
        or "СОСУД" in name
        or "VESSEL" in name
        or "ГАЗОСЕПАРАТОР" in name
        or "ЕМКОСТ" in eq_name
        or "ЁМКОСТ" in eq_name
        or object_type in PRESSURE_DEVICE_OBJECT_TYPES
    )


def default_purpose_for_kind(kind: str) -> str | None:
    if kind == "vessel":
        return None
    return default_purpose_for_preset(kind)


def apply_device_terminology(text: str, kind: str) -> str:
    replacements = KIND_REPLACEMENTS.get(kind)
    if not text or not replacements:
        return text
    result = text
    for old, new in replacements:
        result = result.replace(old, new)
    return result


def _replace_paragraph_text(paragraph, kind: str) -> None:
    replacements = KIND_REPLACEMENTS.get(kind)
    if not replacements:
        return
    full = paragraph.text
    if not full or "сосуд" not in full.lower():
        return
    new_text = apply_device_terminology(full, kind)
    if new_text == full:
        return
    for run in paragraph.runs:
        run.text = ""
    if paragraph.runs:
        paragraph.runs[0].text = new_text
    else:
        paragraph.add_run(new_text)


def apply_device_terminology_to_document(doc, kind: str) -> None:
    """Замена «сосуд» на предметную лексику во всём документе."""
    if kind not in KIND_REPLACEMENTS:
        return
    for paragraph in doc.paragraphs:
        _replace_paragraph_text(paragraph, kind)
    for table in doc.tables:
        for row in table.rows:
            for cell in row.cells:
                for paragraph in cell.paragraphs:
                    _replace_paragraph_text(paragraph, kind)
